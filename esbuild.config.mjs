import esbuild from "esbuild";
import { writeFile } from "node:fs/promises";
import { portableTelegram } from "./scripts/bundle-dependencies.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";
const test = process.argv[2] === "test";
const mainPath = "main.js";

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	platform: "node",
	plugins: [portableTelegram],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	metafile: prod,
	write: !prod,
	outfile: mainPath,
});

if (prod || test) {
	try {
		const result = await context.rebuild();
		if (prod) {
			const excluded =
				/(?:^|\/)node_modules\/(?:telegram|node-machine-id|node-telegram-bot-api|node-localstorage|store2|bufferutil|utf-8-validate|@cypress\/request(?:-promise)?|@cifrante)(?:\/|$)|(?:cifrante\.node\.cjs|\.node)$/;
			for (const input of Object.keys(result.metafile.inputs)) {
				if (excluded.test(input.replaceAll("\\", "/")))
					throw new Error(`Unexpected dependency in plugin bundle: ${input}`);
			}
			for (const output of Object.values(result.metafile.outputs)) {
				if (output.imports.some((entry) => /^(?:node:)?child_process$/.test(entry.path))) {
					throw new Error("The plugin bundle must not depend on child_process.");
				}
			}
			for (const file of result.outputFiles) await writeFile(file.path, file.contents);
		}
	} finally {
		await context.dispose();
	}
} else {
	await context.watch();
}
